#!/usr/bin/env node

/**
 * MenuSheet build step: generate the Cloudflare Pages routing table.
 *
 * Why this exists at all:
 *
 * The site is a static export on Cloudflare Pages, and Pages applies the FIRST
 * matching rule in public/_redirects, with a matching rule taking precedence
 * over a static asset at the same path. So a catch-all like `/r/* 200
 * /r-shell.html` would shadow the real pre-rendered pages under out/r/. Every
 * id that has a pre-rendered page therefore needs its own rule ahead of the
 * catch-alls, and that list can only be produced at build time.
 *
 * What it reads:  data/restaurants.json — the hand-maintained list of ids that
 *                 should get a pre-rendered page.
 * What it writes: public/_redirects — the routing table.
 *
 * It deliberately does NOT write data/restaurants.json. An earlier version
 * normalised the manifest and wrote it back on every build, which dirtied the
 * working tree for no benefit and made it look like the roster was generated
 * when it is in fact hand-edited. KV is the roster; this file is only the
 * pre-render list.
 *
 * Because the manifest is committed and always exists, this can never fail a
 * build. A missing or broken manifest degrades to "nothing is pre-rendered",
 * and the /r-shell catch-all serves every restaurant from the API.
 *
 * Seeding a fresh environment: the KV roster has to be populated once, from the
 * same data/restaurants.json, with `npm run seed` in the worker/ directory.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'data', 'restaurants.json');
const REDIRECTS_PATH = path.join(ROOT, 'public', '_redirects');

/**
 * Ids are used in a URL path and in a Pages routing rule, so anything with a
 * slash, whitespace or a wildcard character in it is dropped rather than
 * producing a rule that silently never matches.
 */
function isRoutableId(id) {
  return /^[A-Za-z0-9._-]{1,64}$/.test(id);
}

function readIds() {
  if (!fs.existsSync(MANIFEST_PATH)) return [];
  const parsed = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  if (!Array.isArray(parsed.restaurants)) return [];
  return parsed.restaurants
    .map((r) => String(r.restaurant_id ?? '').trim())
    .filter(Boolean);
}

function writeRedirects(ids) {
  const known = ids.filter(isRoutableId);
  const skipped = ids.filter((id) => !isRoutableId(id));

  const lines = [
    '# Generated by scripts/generate-static-data.js — do not edit by hand.',
    '#',
    '# Cloudflare Pages applies the first matching rule, and a matching rule wins',
    '# over a static asset at the same path. So every path that has a real',
    '# pre-rendered page needs its own rule ahead of the catch-alls, otherwise the',
    '# catch-all would shadow it.',
    '',
    '# Restaurants listed in data/restaurants.json keep their pre-rendered page,',
    '# with server-rendered metadata and JSON-LD.',
  ];

  for (const id of known) {
    lines.push(`/r/${id} 200 /r/${id}.html`);
  }

  lines.push('');
  lines.push('# /admin/restaurants/new is a real static route and must be listed before');
  lines.push('# the admin catch-all below, or the catch-all would shadow it.');
  lines.push('/admin/restaurants/new 200 /admin/restaurants/new.html');
  lines.push('');
  lines.push('# Catch-alls. Anything not pre-rendered resolves entirely from the API,');
  lines.push('# which is why a restaurant onboarded after this build is live at its QR');
  lines.push('# URL without a redeploy.');
  lines.push('/r/* 200 /r-shell.html');
  lines.push('/admin/restaurants/* 200 /admin/restaurants/_shell.html');
  lines.push('');

  fs.mkdirSync(path.dirname(REDIRECTS_PATH), { recursive: true });
  fs.writeFileSync(REDIRECTS_PATH, lines.join('\n'));

  return { known: known.length, skipped };
}

function main() {
  const ids = readIds();
  const { known, skipped } = writeRedirects(ids);

  console.log(`[menusheet-build] wrote public/_redirects — ${known} pre-rendered route(s) + 1 catch-all`);
  if (!known) {
    console.log('[menusheet-build] no pre-rendered restaurants; everything resolves through /r-shell');
  }
  if (skipped.length) {
    console.warn(`[menusheet-build] skipped ${skipped.length} id(s) with unsafe characters: ${skipped.join(', ')}`);
    console.warn('[menusheet-build] those restaurants will still be served, via the /r-shell catch-all');
  }
  console.log('[menusheet-build] menus and billing come from the platform API + KV, not from the build');
}

try {
  main();
} catch (err) {
  // A build must never fail because of this file. Without _redirects, Pages
  // serves the static files as-is, which loses the catch-alls but still works
  // for every pre-rendered page.
  console.error('[menusheet-build] unexpected error:', err.message);
  process.exit(0);
}
